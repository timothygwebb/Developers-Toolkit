function Find-Git {
    $gitCmd = Get-Command git -ErrorAction SilentlyContinue
    if ($gitCmd) {
        return $gitCmd.Source
    }
    $gitCandidates = @(
        "$env:ProgramFiles\Git\cmd\git.exe",
        "$env:ProgramFiles\Git\bin\git.exe",
        "${env:ProgramFiles(x86)}\Git\cmd\git.exe"
    )
    foreach ($candidate in $gitCandidates) {
        if (Test-Path -LiteralPath $candidate) {
            return $candidate
        }
    }
    return $null
}

if ($SkipTemplate) {
    $templateStatus = 'Skipped (-SkipTemplate)'
    Write-Host "  $templateStatus"
} else {
    $gitPath = Find-Git
    if (-not $gitPath) {
        $templateStatus = 'Failed: git was not found on PATH or in the usual Git for Windows locations, so the global templateDir could not be set or verified.'
        $templateFailed = $true
        Write-Host "  $templateStatus" -ForegroundColor Red
    } else {
        # Read the existing global templateDir, if any. A missing
        # key makes git exit 1 with no output; that is not an error
        # here, it just means no templateDir is set yet.
        $existingTemplate = & $gitPath config --global --get init.templateDir 2>$null
        if ($LASTEXITCODE -ne 0) {
            $existingTemplate = $null
        }
        if ($existingTemplate) {
            $existingTemplate = $existingTemplate.Trim()
        }
        $effectiveTemplateDir = $null
        $keepExistingConfig = $false
        if ([string]::IsNullOrWhiteSpace($existingTemplate)) {
            $effectiveTemplateDir = $TemplateDir
        } elseif ([string]::Equals($existingTemplate, $TemplateDir, [StringComparison]::OrdinalIgnoreCase)) {
            $effectiveTemplateDir = $TemplateDir
            $keepExistingConfig = $true
        } elseif (Test-Path -LiteralPath $existingTemplate) {
            # A different templateDir already exists. Do not
            # overwrite the global setting; use that template.
            $effectiveTemplateDir = $existingTemplate
            $keepExistingConfig = $true
            Write-Host "  Existing global init.templateDir found: $existingTemplate"
            Write-Host "  Keeping that setting. The hook will be copied into that template instead of $TemplateDir."
        } else {
            $templateStatus = "Skipped: existing global init.templateDir points to a directory that does not exist: $existingTemplate. Global config was NOT overwritten. Clear that setting first, or pass -TemplateDir for the directory you want to use."
            $templateFailed = $true
            Write-Host "  $templateStatus" -ForegroundColor Red
        }

        if ($effectiveTemplateDir) {
            $templateHooksDir = Join-Path $effectiveTemplateDir 'hooks'
            $templateDest = Join-Path $templateHooksDir 'pre-commit'
            if ($DryRun) {
                if (Test-Path -LiteralPath $templateDest) {
                    $tHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $templateDest).Hash
                    if ([string]::Equals($tHash, $sourceHash, [StringComparison]::OrdinalIgnoreCase)) {
                        $templateStatus = "Would keep template as-is (already up to date): $templateDest"
                    } else {
                        $tText = [System.Text.Encoding]::ASCII.GetString([System.IO.File]::ReadAllBytes($templateDest))
                        if ($tText.Contains('pre-commit hook - git commit checker')) {
                            $templateStatus = "Would update template hook: $templateDest"
                        } elseif ($Force) {
                            $templateStatus = "Would force replace template hook: $templateDest"
                        } else {
                            $templateStatus = "Would skip template hook (existing custom hook, use -Force to replace): $templateDest"
                        }
                    }
                } else {
                    $templateStatus = "Would copy hook to template: $templateDest"
                    if (-not $keepExistingConfig) {
                        $templateStatus += ", and set global init.templateDir to $effectiveTemplateDir"
                    }
                }
                Write-Host "  $templateStatus"
                Write-Host "  Dry run only - no template file was written and no global config was changed."
            } else {
                try {
                    if (-not (Test-Path -LiteralPath $templateHooksDir)) {
                        New-Item -ItemType Directory -Path $templateHooksDir -Force | Out-Null
                    }
                    $templateAction = 'Installed'
                    if (Test-Path -LiteralPath $templateDest) {
                        $tHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $templateDest).Hash
                        if ([string]::Equals($tHash, $sourceHash, [StringComparison]::OrdinalIgnoreCase)) {
                            $templateAction = 'AlreadyUpToDate'
                        } else {
                            $tText = [System.Text.Encoding]::ASCII.GetString([System.IO.File]::ReadAllBytes($templateDest))
                            $tIsOurs = $tText.Contains('pre-commit hook - git commit checker')
                            if (-not $tIsOurs -and -not $Force) {
                                throw "Template already has a custom pre-commit hook at $templateDest. Re-run with -Force to replace it (it will be backed up first)."
                            }
                            $tStamp = Get-Date -Format yyyyMMdd-HHmmss
                            $tBackup = "$templateDest.bak-$tStamp"
                            $tN = 1
                            while (Test-Path -LiteralPath $tBackup) {
                                $tBackup = "$templateDest.bak-$tStamp-$tN"
                                $tN += 1
                            }
                            Copy-Item -LiteralPath $templateDest -Destination $tBackup -Force
                            Write-Host "  Backed up existing template hook to $tBackup"
                            if ($tIsOurs) {
                                $templateAction = 'Updated'
                            } else {
                                $templateAction = 'ForceReplaced'
                            }
                        }
                    }
                    if ($templateAction -ne 'AlreadyUpToDate') {
                        [System.IO.File]::WriteAllBytes($templateDest, $hookBytes)
                        $tWrittenHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $templateDest).Hash
                        if (-not [string]::Equals($tWrittenHash, $sourceHash, [StringComparison]::OrdinalIgnoreCase)) {
                            throw "SHA256 mismatch after copy to template $templateDest"
                        }
                        Set-HookExecutable -Path $templateDest
                    }
                    if (-not $keepExistingConfig) {
                        & $gitPath config --global init.templateDir $effectiveTemplateDir 2>$null
                        if ($LASTEXITCODE -ne 0) {
                            throw "git config --global init.templateDir failed."
                        }
                        $verifyConfig = & $gitPath config --global --get init.templateDir 2>$null
                        if ($LASTEXITCODE -ne 0 -or -not [string]::Equals($verifyConfig.Trim(), $effectiveTemplateDir, [StringComparison]::OrdinalIgnoreCase)) {
                            throw "Global init.templateDir did not read back as $effectiveTemplateDir after setting it."
                        }
                    }
                    # Verify with a throwaway git init, then delete it.
                    $testDir = Join-Path $env:TEMP ("git-template-test-" + [System.Guid]::NewGuid().ToString('N').Substring(0, 8))
                    try {
                        & $gitPath init -q $testDir 2>$null
                        if ($LASTEXITCODE -ne 0) {
                            throw "Test git init failed in $testDir."
                        }
                        $testHook = Join-Path $testDir '.git\hooks\pre-commit'
                        if (-not (Test-Path -LiteralPath $testHook)) {
                            throw "Test git init did not copy the hook to $testHook."
                        }
                        $testHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $testHook).Hash
                        if (-not [string]::Equals($testHash, $sourceHash, [StringComparison]::OrdinalIgnoreCase)) {
                            throw "Test git init copied a hook with the wrong SHA256."
                        }
                    } finally {
                        if (Test-Path -LiteralPath $testDir) {
                            Remove-Item -LiteralPath $testDir -Recurse -Force -ErrorAction SilentlyContinue
                        }
                    }
                    $templateStatus = "Configured ($templateAction): template hook at $templateDest, global init.templateDir = $effectiveTemplateDir, verified by a test git init."
                    Write-Host "  $templateStatus"
                } catch {
                    $templateStatus = "Failed: $($_.Exception.Message)"
                    $templateFailed = $true
                    Write-Host "  $templateStatus" -ForegroundColor Red
                }
            }
        }
    }
}

Write-Host ""
Write-Host "Summary:"
Write-Host "  Template (future clones): $templateStatus"
Write-Host "  Installed: $($counts.Installed)"
Write-Host "  Updated (older copy of this hook): $($counts.Updated)"
Write-Host "  Force replaced (custom hook, -Force): $($counts.ForceReplaced)"
Write-Host "  Already up to date: $($counts.AlreadyUpToDate)"
Write-Host "  Skipped (existing custom hook): $($counts.SkippedCustom)"
Write-Host "  Skipped (excluded): $($counts.SkippedExcluded)"
Write-Host "  Skipped (not a git repo): $($counts.NoGit)"
Write-Host "  Initialized as a git repo (-InitNonRepos): $($counts.Initialized)"
Write-Host "  Skipped (tool folder / virtual environment, never initialized): $($counts.SkippedVenv)"
Write-Host "  Failed: $($counts.Failed)"
if ($DryRun) {
    Write-Host "  Would install: $($counts.WouldInstall)"
    Write-Host "  Would update: $($counts.WouldUpdate)"
    Write-Host "  Would force replace: $($counts.WouldForceReplace)"
    Write-Host "  Would initialize as a git repo (-InitNonRepos): $($counts.WouldInit)"
    Write-Host "Dry run only - nothing was written."
}
if ($skippedCustom.Count -gt 0) {
    Write-Host ""
    Write-Host "Repos with an existing custom hook, skipped (review these manually, or re-run with -Force):"
    foreach ($name in $skippedCustom) {
        Write-Host "  - $name"
    }
}
if ($failedRepos.Count -gt 0) {
    Write-Host ""
    Write-Host "Failed repos:"
    foreach ($entry in $failedRepos) {
        Write-Host "  - $entry"
    }
}
if ($templateFailed) {
    Write-Host ""
    Write-Host "Template setup did not complete (see the template section above). Existing-repo installs above still stand, but future clones will not get the hook until template setup succeeds or you re-run with -SkipTemplate to accept that."
}
if ($failedRepos.Count -gt 0 -or $templateFailed) {
    exit 1
}
Write-Host ""
Write-Host "Done. Existing repos are listed above, and future clones will get the hook from the template directory."
