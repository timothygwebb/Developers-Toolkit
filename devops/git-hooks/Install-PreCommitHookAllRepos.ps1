#Requires -Version 5.1
<#
.SYNOPSIS
    Installs the fixed pre-commit hook into every local repository
    under a repos root, and into a git template directory so every
    future clone and git init also gets it.

.DESCRIPTION
    Run this script on your Windows machine, from Downloads, next to
    the "pre-commit" file. It needs access to your local clones.

    "All" means: every immediate subdirectory of -ReposRoot that
    contains a .git directory or a .git file (worktree / submodule
    style). It does NOT recurse into subdirectories, so a repo's own
    submodules and nested folders are not treated as separate repos,
    and it does NOT touch bare repos (no working tree, no commits
    to hook).

    Default: $env:USERPROFILE\source\repos

    Non-repos (added 2026-11-04, opt-in with -InitNonRepos):
    by default a folder with no .git is skipped. With
    -InitNonRepos, the script runs git init in that folder, then
    installs the hook into it the same way as any other repo
    (the template, if already configured, may already have
    copied the hook in during init; the explicit install then
    reports AlreadyUpToDate, which is correct). Nothing is
    staged or committed by init, and deleting the new .git
    folder undoes it. Two guard rails stay on even with
    -InitNonRepos: a folder that looks like a tool folder or a
    Python virtual environment (any hidden dot-folder such as
    .vs, or named venv or env, or containing pyvenv.cfg) is
    never initialized, because those are not projects; and a
    folder you pass with -Exclude is never initialized.
    -InitNonRepos is opt-in, not the default,
    because initializing a folder is a new repo, not just a
    hook copy, and a repos root can contain non-project
    folders. In -DryRun, a non-repo is reported as WouldInit
    and no init is run.

    Safety rules, because "all" is a wide blast radius:
    - A repo with NO .git\hooks\pre-commit file gets the hook installed.
    - A repo whose existing hook is already this hook (same SHA256)
      is reported as already up to date and left alone.
    - A repo whose existing hook is an older copy of this hook
      (identified by the header "pre-commit hook - git commit checker")
      is backed up and updated.
    - A repo with a DIFFERENT, custom pre-commit hook is SKIPPED by
      default and listed in the summary for manual review. Replacing
      it silently could destroy checks that repo relies on, including
      hooks generated by pre-commit.com, Husky, or another tool.
      Pass -Force to replace those too (each one is still backed up
      first). Skipped-custom repos do not make the script fail.
    - A failure in one repo is reported and counted, and the loop
      continues with the next repo. It does not abort the whole run.
    - Nothing is committed or pushed. This only writes inside
      .git\hooks, which Git never tracks.

    The hook itself still does what the fixed version does: it
    strips trailing spaces/tabs from staged text files and blocks a
    commit if a secret pattern is found. That whitespace step runs
    in every repo you install it into. In Markdown, two trailing
    spaces are a hard line break, so stripping them changes
    rendering. If you have a repo where trailing whitespace is
    meaningful, exclude that repo with -Exclude, or do not install
    there. The script does not change the hook to skip Markdown
    on its own, because that would change the hook for every repo.

    Source file: by default the script looks for a file named
    "pre-commit" next to this script, then in
    $env:USERPROFILE\Downloads\pre-commit. Use -SourcePath to point
    at another copy explicitly. If no local copy is found, the
    script downloads it from GitHub (see -HookDownloadUrl) to
    Downloads\pre-commit, and only then proceeds. It never
    overwrites a local copy that already exists. The source is
    normalized to LF before copying, and each copy is verified
    by SHA256.

    Download caveat, stated plainly: the default download URLs
    point at hooks/pre-commit in the Developers-Toolkit repository
    (master first, then the toolkit/initial-package branch). That
    file is NOT in the toolkit repo yet, and that repo is still
    private, so an unauthenticated raw.githubusercontent.com
    download will return 404 today. Until the toolkit copy is
    actually published there, download is best-effort only: if
    it fails, the script stops with a clear message and you place
    the pre-commit file in Downloads manually, as before. Pass
    -HookDownloadUrl to point at a different, already-published
    location instead. A downloaded file is only accepted if it
    is non-empty and starts with "#!/bin/sh", so an HTML error
    page can never be installed as a hook.

    Fixed 2026-11-04: the previous version reported every real
    repo as FAILED with "Could not find item ...\.git". That was
    not a missing repo. Test-Path returns true for a hidden .git
    folder, but Get-Item without -Force does not return hidden
    items in Windows PowerShell 5.1, so Get-RealGitDir threw.
    Get-Item and Get-Content now use -Force for .git, and repo
    enumeration uses Get-ChildItem -Force, so hidden .git folders
    are handled. The four folders reported as "not a git repo"
    (example-repo, another-repo) really have no .git
    and are still skipped.

    Future clones (added 2026-11-04): after the existing repos
    are handled, the script also sets up a git template directory
    so future clones and git init operations get the hook
    automatically. How Git templates work, in one paragraph: when
    Git creates a new repository (git init, and git clone, which
    runs git init underneath), it copies the files from the
    template directory into the new .git directory. A file named
    hooks\pre-commit in the template therefore becomes
    .git\hooks\pre-commit in every new clone. The template does
    NOT change existing clones, and re-running git init in an
    existing repo does not overwrite an existing hook there.

    Template defaults: $env:USERPROFILE\.git-templates, with the
    hook at $env:USERPROFILE\.git-templates\hooks\pre-commit.
    The script sets the global config init.templateDir to that
    path, unless a different global templateDir is already set.
    If a different templateDir is already set and that directory
    exists, the script does NOT overwrite your global config: it
    copies the hook into that existing template's hooks folder
    instead, and reports that it kept your setting. If a different
    templateDir is set but that directory does not exist, the
    script skips template setup and reports it, rather than
    silently pointing Git somewhere else. Pass -SkipTemplate to
    skip template setup entirely, or -TemplateDir to choose a
    different template directory explicitly.

    After setting the template up, the script verifies it with a
    throwaway test: it runs git init in a temporary folder, checks
    that .git\hooks\pre-commit was copied there with the correct
    SHA256, then deletes the temporary folder. In -DryRun, no
    template file is written, no global config is changed, and no
    test init is run; the script only reports what it would do.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File $env:USERPROFILE\Downloads\Install-PreCommitHookAllRepos.ps1 -DryRun
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File $env:USERPROFILE\Downloads\Install-PreCommitHookAllRepos.ps1
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File $env:USERPROFILE\Downloads\Install-PreCommitHookAllRepos.ps1 -Exclude 'example-repo'
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File $env:USERPROFILE\Downloads\Install-PreCommitHookAllRepos.ps1 -Force
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File $env:USERPROFILE\Downloads\Install-PreCommitHookAllRepos.ps1 -HookDownloadUrl 'https://raw.githubusercontent.com/timothygwebb/Developers-Toolkit/master/hooks/pre-commit'
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File $env:USERPROFILE\Downloads\Install-PreCommitHookAllRepos.ps1 -SkipTemplate
#>

param(
    [string]$SourcePath = "",
    [string]$ReposRoot = "$env:USERPROFILE\source\repos",
    [string[]]$Exclude = @(),
    [string]$HookDownloadUrl = "",
    [string]$TemplateDir = "$env:USERPROFILE\.git-templates",
    [switch]$Force,
    [switch]$SkipTemplate,
    [switch]$InitNonRepos,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'

function Fail([string]$msg) {
    Write-Host "ERROR: $msg" -ForegroundColor Red
    exit 1
}

$scriptDir = $null
if ($PSScriptRoot) {
    $scriptDir = $PSScriptRoot
} elseif ($MyInvocation.MyCommand.Path) {
    $scriptDir = Split-Path $MyInvocation.MyCommand.Path -Parent
} else {
    $scriptDir = (Get-Location).Path
}

if ([string]::IsNullOrWhiteSpace($SourcePath)) {
    $candidates = @(
        (Join-Path $scriptDir 'pre-commit'),
        (Join-Path "$env:USERPROFILE\Downloads" 'pre-commit')
    )
    foreach ($c in $candidates) {
        if (Test-Path -LiteralPath $c -PathType Leaf) {
            $SourcePath = $c
            break
        }
    }
    if ([string]::IsNullOrWhiteSpace($SourcePath)) {
        # No local copy: download from GitHub, unless this is a
        # dry run, in which case nothing may be written at all.
        if ($DryRun) {
            Fail ("Source file 'pre-commit' not found, and -DryRun is set so no download will be attempted. Checked: " + ($candidates -join '; ') + ". Run without -DryRun to attempt the download, or place the pre-commit file next to this script, or pass -SourcePath.")
        }
        $downloadUrls = @()
        if (-not [string]::IsNullOrWhiteSpace($HookDownloadUrl)) {
            $downloadUrls = @($HookDownloadUrl)
        } else {
            $downloadUrls = @(
                'https://raw.githubusercontent.com/timothygwebb/Developers-Toolkit/master/hooks/pre-commit',
                'https://raw.githubusercontent.com/timothygwebb/Developers-Toolkit/toolkit/initial-package/hooks/pre-commit'
            )
        }
        Write-Host "No local pre-commit file found. Attempting download from GitHub..."
        try {
            [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
        } catch {
            Write-Host "Note: could not force TLS 1.2, continuing with the system default."
        }
        $downloadsDir = Join-Path "$env:USERPROFILE" 'Downloads'
        if (-not (Test-Path -LiteralPath $downloadsDir)) {
            New-Item -ItemType Directory -Path $downloadsDir -Force | Out-Null
        }
        $downloadPath = Join-Path $downloadsDir 'pre-commit'
        $downloaded = $false
        foreach ($url in $downloadUrls) {
            Write-Host "Trying: $url"
            try {
                Invoke-WebRequest -Uri $url -OutFile $downloadPath -UseBasicParsing -ErrorAction Stop | Out-Null
            } catch {
                Write-Host "Download failed from $url : $($_.Exception.Message)"
                Remove-Item -LiteralPath $downloadPath -Force -ErrorAction SilentlyContinue
                continue
            }
            if (-not (Test-Path -LiteralPath $downloadPath -PathType Leaf)) {
                Write-Host "Download produced no file from $url"
                continue
            }
            $downloadBytes = [System.IO.File]::ReadAllBytes($downloadPath)
            if ($downloadBytes.Length -eq 0) {
                Write-Host "Downloaded file from $url is empty, discarding it."
                Remove-Item -LiteralPath $downloadPath -Force -ErrorAction SilentlyContinue
                continue
            }
            $dlFirstEnd = [Array]::IndexOf($downloadBytes, [byte]10)
            if ($dlFirstEnd -lt 0) {
                $dlFirstEnd = $downloadBytes.Length
            }
            $dlFirstLine = [System.Text.Encoding]::ASCII.GetString($downloadBytes, 0, $dlFirstEnd).TrimEnd("`r")
            if (-not $dlFirstLine.StartsWith('#!/bin/sh')) {
                Write-Host "Downloaded file from $url does not start with '#!/bin/sh' (likely an error page), discarding it."
                Remove-Item -LiteralPath $downloadPath -Force -ErrorAction SilentlyContinue
                continue
            }
            $SourcePath = $downloadPath
            $downloaded = $true
            Write-Host "Downloaded pre-commit hook from $url to $downloadPath"
            break
        }
        if (-not $downloaded) {
            Fail ("Could not download the pre-commit hook from GitHub. Tried: " + ($downloadUrls -join '; ') + ". This is expected today: hooks/pre-commit is not yet published in Developers-Toolkit, and that repo is private, so unauthenticated raw download returns 404. Place the pre-commit file next to this script or in Downloads, pass -SourcePath, or pass -HookDownloadUrl for an already-published location.")
        }
    }
}
if (-not (Test-Path -LiteralPath $SourcePath -PathType Leaf)) {
    Fail "Source file not found: $SourcePath"
}
if (-not (Test-Path -LiteralPath $ReposRoot -PathType Container)) {
    Fail "Repos root not found: $ReposRoot"
}
Write-Host "Source: $SourcePath"
Write-Host "Repos root: $ReposRoot"
if ($Exclude.Count -gt 0) {
    Write-Host "Excluded repos: $($Exclude -join ', ')"
}
if ($Force) {
    Write-Host "Force: ON - existing custom hooks will be backed up and replaced."
} else {
    Write-Host "Force: OFF - existing custom hooks will be skipped and listed."
}
if ($DryRun) {
    Write-Host "Dry run only - nothing will be written."
}

$rawBytes = [System.IO.File]::ReadAllBytes($SourcePath)
if ($rawBytes.Length -eq 0) {
    Fail "Source file is empty: $SourcePath"
}
$firstLineEnd = [Array]::IndexOf($rawBytes, [byte]10)
if ($firstLineEnd -lt 0) {
    $firstLineEnd = $rawBytes.Length
}
$firstLine = [System.Text.Encoding]::ASCII.GetString($rawBytes, 0, $firstLineEnd).TrimEnd("`r")
if (-not $firstLine.StartsWith('#!/bin/sh')) {
    Fail "Source file does not start with '#!/bin/sh'. First line was: $firstLine"
}
$converted = New-Object System.Collections.Generic.List[byte]
$i = 0
while ($i -lt $rawBytes.Length) {
    $b = $rawBytes[$i]
    if ($b -eq 13) {
        $converted.Add([byte]10)
        if (($i + 1) -lt $rawBytes.Length -and $rawBytes[$i + 1] -eq 10) {
            $i += 2
        } else {
            $i += 1
        }
    } else {
        $converted.Add($b)
        $i += 1
    }
}
$hookBytes = $converted.ToArray()
if ($hookBytes.Length -ne $rawBytes.Length) {
    Write-Host "Note: normalized line endings to LF (source had CRLF/CR bytes)."
}
$sha = [System.Security.Cryptography.SHA256]::Create()
$hashBytes = $sha.ComputeHash($hookBytes)
$sb = New-Object System.Text.StringBuilder
foreach ($hb in $hashBytes) {
    [void]$sb.AppendFormat('{0:x2}', $hb)
}
$sourceHash = $sb.ToString()
$sha.Dispose()
Write-Host "Source SHA256: $sourceHash"
Write-Host ""

# Find Git Bash once, for chmod +x, instead of once per repo.
# Fixed 2026-11-04: do NOT fall back to Get-Command bash. On a
# Windows machine with WSL installed, Get-Command bash returns
# C:\Windows\System32\bash.exe, which is the WSL launcher, not
# Git Bash. WSL cannot see a Windows path written as
# C:/Users/<username>/..., so chmod failed with "No such file or
# directory", and with $ErrorActionPreference = 'Stop' that
# stderr became a terminating error, so every repo was reported
# FAILED even though its hook file had already been written and
# verified by SHA256 just before the chmod step. Git Bash is
# therefore searched only in its own install locations, including
# the per-user install under LOCALAPPDATA. If no Git Bash is
# found, chmod is simply skipped: Git for Windows normally runs
# .git/hooks/pre-commit without a Unix executable bit when
# core.fileMode is false (the Windows default), so chmod is
# best-effort only and must never fail an install.
$bashPath = $null
$gitBashCandidates = @(
    "$env:ProgramFiles\Git\bin\bash.exe",
    "$env:ProgramFiles\Git\usr\bin\bash.exe",
    "${env:ProgramFiles(x86)}\Git\bin\bash.exe",
    "$env:LOCALAPPDATA\Programs\Git\bin\bash.exe",
    "$env:LOCALAPPDATA\Programs\Git\usr\bin\bash.exe"
)
foreach ($candidate in $gitBashCandidates) {
    if (Test-Path -LiteralPath $candidate) {
        $bashPath = $candidate
        break
    }
}

function Convert-ToGitBashPath {
    param([string]$WindowsPath)
    if ($WindowsPath -match '^([A-Za-z]):\\(.*)$') {
        return '/' + $matches[1].ToLower() + '/' + ($matches[2] -replace '\\', '/')
    }
    return $WindowsPath.Replace('\', '/')
}

function Set-HookExecutable {
    param([string]$Path)
    # Best-effort only. Never throws, never fails an install.
    if (-not $bashPath) {
        Write-Host "  chmod skipped: Git Bash not found. Git for Windows normally runs the hook anyway."
        return
    }
    $unixPath = Convert-ToGitBashPath -WindowsPath $Path
    $oldEAP = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        & $bashPath -c "chmod +x '$unixPath'" *> $null
        if ($LASTEXITCODE -ne 0) {
            Write-Host "  Warning: chmod +x failed for $Path (exit $LASTEXITCODE). Not fatal: the file was already written and verified, and Git for Windows normally runs the hook without a Unix executable bit."
        }
    } catch {
        Write-Host "  Warning: chmod +x could not run for $Path : $($_.Exception.Message). Not fatal: the file was already written and verified."
    } finally {
        $ErrorActionPreference = $oldEAP
    }
}

function Get-RealGitDir {
    param([string]$RepoPath)
    $gitPath = Join-Path $RepoPath '.git'
    if (-not (Test-Path -LiteralPath $gitPath)) {
        return $null
    }
    # .git is hidden. Get-Item without -Force does not return
    # hidden items in Windows PowerShell 5.1, which is why the
    # previous version failed here even though Test-Path had
    # already returned true for the same path.
    if ((Get-Item -LiteralPath $gitPath -Force) -is [System.IO.DirectoryInfo]) {
        return $gitPath
    }
    # .git is a file: "gitdir: <path>"
    $gitFileLine = Get-Content -LiteralPath $gitPath -TotalCount 1 -Force
    if (-not $gitFileLine -or -not $gitFileLine.StartsWith('gitdir:')) {
        throw ".git file at $gitPath does not contain a gitdir line."
    }
    $gitDirValue = $gitFileLine.Substring(7).Trim()
    if ([System.IO.Path]::IsPathRooted($gitDirValue)) {
        return $gitDirValue
    }
    return (Join-Path $RepoPath $gitDirValue)
}

function Install-OneRepo {
    param([string]$RepoPath)
    # Returns a status string. Throws on failure; the caller catches
    # it, records the repo as Failed, and moves on to the next repo.
    $realGitDir = Get-RealGitDir -RepoPath $RepoPath
    if (-not $realGitDir) {
        return 'NoGit'
    }
    $hooksDir = Join-Path $realGitDir 'hooks'
    $dest = Join-Path $hooksDir 'pre-commit'

    if (Test-Path -LiteralPath $dest) {
        $existingHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $dest).Hash
        if ([string]::Equals($existingHash, $sourceHash, [StringComparison]::OrdinalIgnoreCase)) {
            return 'AlreadyUpToDate'
        }
        $existingText = [System.Text.Encoding]::ASCII.GetString([System.IO.File]::ReadAllBytes($dest))
        $isOurs = $existingText.Contains('pre-commit hook - git commit checker')
        if (-not $isOurs -and -not $Force) {
            return 'SkippedCustom'
        }
        if ($DryRun) {
            if ($isOurs) {
                return 'WouldUpdate'
            }
            return 'WouldForceReplace'
        }
        $stamp = Get-Date -Format yyyyMMdd-HHmmss
        $backup = "$dest.bak-$stamp"
        $n = 1
        while (Test-Path -LiteralPath $backup) {
            $backup = "$dest.bak-$stamp-$n"
            $n += 1
        }
        Copy-Item -LiteralPath $dest -Destination $backup -Force
        Write-Host "  backed up existing hook to $backup"
        if ($isOurs) {
            $statusAfterWrite = 'Updated'
        } else {
            $statusAfterWrite = 'ForceReplaced'
        }
    } else {
        if ($DryRun) {
            return 'WouldInstall'
        }
        $statusAfterWrite = 'Installed'
    }

    if (-not (Test-Path -LiteralPath $hooksDir)) {
        New-Item -ItemType Directory -Path $hooksDir -Force | Out-Null
    }
    [System.IO.File]::WriteAllBytes($dest, $hookBytes)
    $writtenHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $dest).Hash
    if (-not [string]::Equals($writtenHash, $sourceHash, [StringComparison]::OrdinalIgnoreCase)) {
        throw "SHA256 mismatch after copy to $dest (wrote $writtenHash, expected $sourceHash)"
    }
    Set-HookExecutable -Path $dest
    return $statusAfterWrite
}

function Find-GitExecutable {
    $gitCmd = Get-Command git -ErrorAction SilentlyContinue
    if ($gitCmd) {
        return $gitCmd.Source
    }
    $gitCandidates = @(
        "$env:ProgramFiles\Git\cmd\git.exe",
        "$env:ProgramFiles\Git\bin\git.exe",
        "${env:ProgramFiles(x86)}\Git\cmd\git.exe",
        "$env:LOCALAPPDATA\Programs\Git\cmd\git.exe"
    )
    foreach ($candidate in $gitCandidates) {
        if (Test-Path -LiteralPath $candidate) {
            return $candidate
        }
    }
    return $null
}

function Test-IsToolFolderDir {
    param([System.IO.DirectoryInfo]$Dir)
    # Fixed 2026-11-04, after a real run initialized .vs: a
    # repos-root folder that is not a project must never be
    # initialized, even with -InitNonRepos. That covers Python
    # virtual environments (.venv, venv, env, or pyvenv.cfg)
    # and any hidden dot-folder such as .vs, which is Visual
    # Studio local cache/metadata, not a project. A legitimate
    # project at a repos root almost never starts with a dot;
    # if one ever does, initialize it by hand with git init.
    if ($Dir.Name.StartsWith('.')) {
        return $true
    }
    if ($Dir.Name -eq 'venv' -or $Dir.Name -eq 'env') {
        return $true
    }
    return (Test-Path -LiteralPath (Join-Path $Dir.FullName 'pyvenv.cfg'))
}

function Initialize-GitRepo {
    param([string]$RepoPath)
    $gitExe = Find-GitExecutable
    if (-not $gitExe) {
        throw "git was not found on PATH or in the usual Git for Windows locations, so git init could not run."
    }
    $oldEAP = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        & $gitExe init $RepoPath *> $null
        if ($LASTEXITCODE -ne 0) {
            throw "git init failed for $RepoPath (exit $LASTEXITCODE)."
        }
    } finally {
        $ErrorActionPreference = $oldEAP
    }
    if (-not (Test-Path -LiteralPath (Join-Path $RepoPath '.git'))) {
        throw "git init reported success for $RepoPath but no .git was created."
    }
}

$repoDirs = Get-ChildItem -LiteralPath $ReposRoot -Directory -Force | Sort-Object Name
if ($repoDirs.Count -eq 0) {
    Fail "No subdirectories found under $ReposRoot"
}

$counts = @{
    Installed = 0
    Updated = 0
    ForceReplaced = 0
    AlreadyUpToDate = 0
    SkippedCustom = 0
    SkippedExcluded = 0
    NoGit = 0
    Initialized = 0
    WouldInit = 0
    SkippedVenv = 0
    Failed = 0
    WouldInstall = 0
    WouldUpdate = 0
    WouldForceReplace = 0
}
$skippedCustom = @()
$failedRepos = @()

foreach ($dir in $repoDirs) {
    $repoName = $dir.Name
    if ($Exclude -contains $repoName) {
        Write-Host "$repoName : excluded"
        $counts.SkippedExcluded += 1
        continue
    }
    # Only immediate subdirectories with a .git entry are repos.
    # This also skips bare repos, which have no .git entry.
    # With -InitNonRepos, a non-repo is initialized first, then
    # falls through to the normal hook install below. Without
    # it, a non-repo is skipped, as before. A virtualenv folder
    # is never initialized, even with -InitNonRepos.
    $gitPath = Join-Path $dir.FullName '.git'
    if (-not (Test-Path -LiteralPath $gitPath)) {
        if (Test-IsToolFolderDir -Dir $dir) {
            Write-Host "$repoName : not a git repo (no .git), skipped (hidden tool folder or virtual environment; -InitNonRepos does not initialize these)"
            $counts.SkippedVenv += 1
            continue
        }
        if (-not $InitNonRepos) {
            Write-Host "$repoName : not a git repo (no .git), skipped"
            $counts.NoGit += 1
            continue
        }
        if ($DryRun) {
            Write-Host "$repoName : not a git repo, would initialize with git init (-InitNonRepos)"
            $counts.WouldInit += 1
            continue
        }
        try {
            Initialize-GitRepo -RepoPath $dir.FullName
            Write-Host "$repoName : initialized git repo with git init"
            $counts.Initialized += 1
        } catch {
            Write-Host "$repoName : FAILED - $($_.Exception.Message)" -ForegroundColor Red
            $counts.Failed += 1
            $failedRepos += "$repoName ($($_.Exception.Message))"
            continue
        }
    }
    try {
        $status = Install-OneRepo -RepoPath $dir.FullName
        Write-Host "$repoName : $status"
        if ($counts.ContainsKey($status)) {
            $counts[$status] += 1
        } else {
            $counts.Failed += 1
            $failedRepos += "$repoName (unknown status: $status)"
        }
        if ($status -eq 'SkippedCustom') {
            $skippedCustom += $repoName
        }
    } catch {
        Write-Host "$repoName : FAILED - $($_.Exception.Message)" -ForegroundColor Red
        $counts.Failed += 1
        $failedRepos += "$repoName ($($_.Exception.Message))"
    }
}

